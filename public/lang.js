class Lang {
  constructor(defaultLanguage = 'tr') {
    this.currentLanguage = defaultLanguage;
    this.translations = translations;
    this.loadLanguage();
  }

  loadLanguage() {
    const savedLanguage = localStorage.getItem('language');
    if (savedLanguage && this.translations[savedLanguage]) {
      this.currentLanguage = savedLanguage;
    }
  }

  setLanguage(language) {
    if (this.translations[language]) {
      this.currentLanguage = language;
      localStorage.setItem('language', language);
      this.updateUI();
      return true;
    }
    return false;
  }

  getLanguage() {
    return this.currentLanguage;
  }

  t(key) {
    const translation = this.translations[this.currentLanguage][key];
    if (translation) {
      return translation;
    }
    // Fallback to English if key not found in current language
    const fallback = this.translations['en'][key];
    if (fallback) {
      return fallback;
    }
    // Return key if not found anywhere
    return key;
  }

  getAvailableLanguages() {
    return Object.keys(this.translations);
  }

  updateUI() {
    // Update HTML lang attribute
    document.documentElement.lang = this.currentLanguage;

    // Update all elements with data-lang attribute
    document.querySelectorAll('[data-lang]').forEach(element => {
      const key = element.getAttribute('data-lang');
      element.textContent = this.t(key);
    });

    // Update label elements with span children
    document.querySelectorAll('label span[data-lang]').forEach(span => {
      const key = span.getAttribute('data-lang');
      span.textContent = this.t(key);
    });

    // Update placeholders
    document.querySelectorAll('[data-placeholder]').forEach(element => {
      const key = element.getAttribute('data-placeholder');
      element.placeholder = this.t(key);
    });

    // Update version info
    const versionInfo = document.getElementById('version-info');
    if (versionInfo) {
      versionInfo.textContent = `${this.t('version')}: ${systemVersion || this.t('loading')}`;
    }

    // Update tab buttons
    document.querySelectorAll('.tab-btn').forEach(btn => {
      const tab = btn.getAttribute('data-tab');
      if (tab) {
        btn.textContent = this.t(tab);
      }
    });

    // Update special buttons with innerHTML structure
    const trueLiveBtn = document.getElementById('true-live-btn');
    if (trueLiveBtn && !trueLiveBtn.classList.contains('active')) {
      trueLiveBtn.innerHTML = '🎙️ <span data-lang="trueLiveButton">' + this.t('trueLiveButton') + '</span>';
      trueLiveBtn.title = this.t('trueLiveButton');
    } else if (trueLiveBtn && trueLiveBtn.classList.contains('active')) {
      trueLiveBtn.title = this.t('trueLiveActiveButton');
    }

    const liveConnectBtn = document.getElementById('live-connect-btn');
    if (liveConnectBtn) {
      // Show when True Live mode is off; hide when it is on.
      const trueLiveBtn = document.getElementById('true-live-btn');
      if (trueLiveBtn && trueLiveBtn.classList.contains('active')) {
        liveConnectBtn.style.display = 'none';
      } else {
        liveConnectBtn.style.display = 'inline-block';
        liveConnectBtn.innerHTML = '🎙️ <span data-lang="liveMicrophoneButton">' + this.t('liveMicrophoneButton') + '</span>';
        liveConnectBtn.title = this.t('liveMicrophoneButton');
      }
    }

    const micBtn = document.getElementById('mic-btn');
    if (micBtn && !micBtn.classList.contains('active')) {
      micBtn.innerHTML = '🎙️ <span data-lang="microphoneButton">' + this.t('microphoneButton') + '</span>';
      micBtn.title = this.t('microphoneButton');
    } else if (micBtn && micBtn.classList.contains('active')) {
      micBtn.title = this.t('microphoneActiveButton');
    }

    // Update elements with data-title attribute
    document.querySelectorAll('[data-title]').forEach(element => {
      const key = element.getAttribute('data-title');
      element.title = this.t(key);
    });

    // Refresh cron list and agent list
    if (typeof updateCronList === 'function') updateCronList();
    if (typeof updateAgentList === 'function') updateAgentList();
    document.dispatchEvent(new CustomEvent('language-changed', { detail: { language: this.currentLanguage } }));
  }
}

